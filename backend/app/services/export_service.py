from __future__ import annotations

import json

from app.schemas.review import FindingResponse, ReviewDetailResponse

_SEVERITY_ORDER = ("critical", "high", "medium", "low")
_CATEGORY_LABELS = {
    "bug": "Bugs and logic",
    "security": "Security",
    "performance": "Performance",
    "error_handling": "Error handling",
    "concurrency": "Concurrency and resources",
    "maintainability": "Maintainability",
    "code_quality": "Code quality",
}


def render_json(review: ReviewDetailResponse) -> str:
    return json.dumps(review.model_dump(mode="json"), indent=2) + "\n"


def render_markdown(review: ReviewDetailResponse) -> str:
    lines = [
        f"# {review.title}",
        "",
        "This export was generated by Patchline from a stored review. Findings come from a language model and are not a statement that the change is safe, correct, or ready to ship.",
        "",
        f"- Status: {review.status}",
        f"- Source: {review.source_type}",
    ]
    if review.source_ref:
        lines.append(f"- Reference: {review.source_ref}")
    lines.append(f"- Created: {review.created_at.isoformat()}")
    if review.model:
        provider = review.provider or "unknown"
        lines.append(f"- Model: {provider} / {review.model}")
    if review.prompt_version:
        lines.append(f"- Prompt: {review.prompt_version}")
    if review.metadata.pull_request and review.metadata.pull_request.url:
        lines.append(f"- Pull request: {review.metadata.pull_request.url}")
    lines.extend(["", "## Summary", "", review.summary or "_No summary was stored._"])
    if review.context_limitations:
        lines.extend(["", "## Context limitations", "", review.context_limitations])
    if review.error_message:
        lines.extend(["", "## Error", "", review.error_message])

    if review.metadata.files:
        lines.extend(["", "## Files", ""])
        for item in review.metadata.files:
            flags = []
            if item.binary:
                flags.append("binary")
            if item.omitted:
                flags.append("text patch omitted")
            suffix = f" ({', '.join(flags)})" if flags else ""
            lines.append(
                f"- `{item.path}` — {item.status}, +{item.additions} / -{item.deletions}{suffix}"
            )

    lines.extend(["", "## Findings", ""])
    if not review.findings:
        lines.append("No findings were stored for this review.")
    else:
        grouped: dict[str, list[FindingResponse]] = {severity: [] for severity in _SEVERITY_ORDER}
        for finding in review.findings:
            grouped.setdefault(finding.severity, []).append(finding)
        for severity in list(grouped):
            items = grouped[severity]
            if not items:
                continue
            lines.extend([f"### {severity.capitalize()} ({len(items)})", ""])
            for finding in items:
                lines.extend(_finding_markdown(finding))
    lines.append("")
    return "\n".join(lines)


def _finding_markdown(finding: FindingResponse) -> list[str]:
    location = finding.file_path or "No file path"
    if finding.line_start is not None:
        if finding.line_end and finding.line_end != finding.line_start:
            location = f"{location}:{finding.line_start}-{finding.line_end}"
        else:
            location = f"{location}:{finding.line_start}"
    category = _CATEGORY_LABELS.get(finding.category, finding.category)
    lines = [
        f"#### {finding.title}",
        "",
        f"- Kind: {finding.kind}",
        f"- Category: {category}",
        f"- Location: `{location}`",
        f"- Confidence: {finding.confidence:.2f}",
    ]
    if finding.insufficient_context:
        lines.append("- The model marked the available context as insufficient for this item.")
    lines.extend(["", finding.explanation, "", "**Recommended fix**", "", finding.recommended_fix, ""])
    if finding.code_snippet:
        lines.extend(["**Snippet**", "", _fence(finding.code_snippet), ""])
    if finding.suggested_patch:
        lines.extend(["**Suggested patch**", "", _fence(finding.suggested_patch), ""])
    return lines


def _fence(code: str) -> str:
    tick = "```"
    while tick in code:
        tick += "`"
    return f"{tick}\n{code}\n{tick}"
